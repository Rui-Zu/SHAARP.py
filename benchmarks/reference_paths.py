"""Resolve file paths recorded inside the Mathematica reference payloads.

Several reference JSONs carry a pointer to a companion file (``mapping_path``: the case-input
mapping that the stage references are keyed against). The exporters wrote that pointer as an
absolute path on the machine that produced the reference, which only resolves on that machine --
even though the companion file ships inside this repository and sits next to the reference itself.

Payloads now record a repository-relative POSIX path. ``resolve_reference_path`` accepts that form
and still accepts a legacy absolute value by falling back to the basename beside the reference
directory, so a payload regenerated by an older exporter continues to load.
"""
from __future__ import annotations

from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[1]
REF_DIR = ROOT / "benchmarks" / "mathematica_reference"


def resolve_reference_path(value: str | Path, *, base: Path = REF_DIR) -> Path:
    """Return the file ``value`` refers to, resolved against THIS checkout.

    Tries, in order: the value relative to the repository root, then the value as given (an
    absolute path that happens to exist), then its basename inside ``base``.
    """
    raw = PurePosixPath(str(value).replace("\\", "/"))
    for candidate in (ROOT / raw, Path(str(value)), base / raw.name):
        if candidate.is_file():
            return candidate
    raise FileNotFoundError(
        f"reference path {str(value)!r} resolves to no file in {ROOT} "
        f"(looked for it relative to the repository root and as {base / raw.name})")


def to_reference_value(path: Path) -> str:
    """Render ``path`` for storage inside a reference payload.

    Repository-relative POSIX when the path is inside the repository, so a payload regenerated on
    one machine loads on every other.
    """
    resolved = Path(path).resolve()
    try:
        return resolved.relative_to(ROOT).as_posix()
    except ValueError:
        return resolved.name
